# Импортируем класс питомца из соседнего файла tamagochi.py.
from tamagochi import Tamagochi

# Создаём экземпляр класса. Python вызывает __init__, который принимает
# имя питомца и задаёт начальные значения его характеристик.
t = Tamagochi("Тузик")

# Читаем имя через публичный метод: прямого обращения к __name не требуется.
# При первом вызове будет напечатано имя, переданное при создании: Тузик.
print(t.get_name())

# Меняем имя через метод, который сначала проверяет его длину.
# Строка "xyz" проходит проверку, поэтому сохраняется как новое имя.
t.set_name("xyz")

# Обращаемся к тому же объекту повторно: теперь get_name вернёт "xyz".
print(t.get_name())
