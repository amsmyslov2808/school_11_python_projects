# Класс объединяет состояние виртуального питомца и методы работы с ним.
# У каждого созданного экземпляра будут собственное имя и характеристики.
class Tamagochi:
    # Аннотации описывают ожидаемые типы, но не создают значения атрибутов
    # и не обеспечивают автоматическую проверку типов во время выполнения.
    # Два начальных подчёркивания включают преобразование имени (name mangling):
    # например, __name становится _Tamagochi__name. Это помогает избежать
    # случайного доступа и конфликтов имён в наследниках, но не запрещает доступ.
    __name: str
    __hunger: int
    __energy: int
    __happiness: int

    def __init__(self, name: str):
        # __init__ вызывается при создании экземпляра Tamagochi(name).
        # self — ссылка на конкретный экземпляр, которому принадлежат данные.
        # Здесь имя сохраняется напрямую: проверка из set_name не вызывается.
        self.__name = name

        # Начальные значения состояния питомца: голод, энергия и счастье.
        # В текущем классе методы изменения этих трёх характеристик ещё не заданы.
        self.__hunger = 50
        self.__energy = 100
        self.__happiness = 50

    def set_name(self, name: str):
        # Сеттер — метод изменения значения с проверкой входных данных.
        # Допустимая длина имени — от 2 до 30 символов включительно.
        # Условие с or срабатывает, если нарушена хотя бы одна граница.
        if len(name) < 2 or len(name) > 30:
            print("Ошибка. Имя должно быть длинной от 2 до 30 сиволов")
            # Досрочно завершаем метод: старое имя при ошибке сохраняется.
            return

        # Эта строка выполняется только после успешной проверки длины.
        self.__name = name

    def get_name(self) -> str:
        # Геттер возвращает текущее имя, позволяя читать его через метод класса.
        # Аннотация -> str указывает ожидаемый тип возвращаемого значения.
        return self.__name
