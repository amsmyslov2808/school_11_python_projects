# dataclass автоматически создаёт служебный код класса, например конструктор __init__.
from dataclasses import dataclass

# Тип date нужен для хранения даты выпуска товара.
from datetime import date


# slots=True запрещает случайно добавлять объекту неизвестные поля с опечатками.
@dataclass(slots=True)
class Product:
    """Карточка одного товара — как одна заполненная строка в таблице магазина.

    Декоратор ``@dataclass`` сам создаёт метод ``__init__``, поэтому объект можно
    собрать простым вызовом ``Product(icon=..., name=..., ...)``. Все поля ниже
    являются характеристиками одной товарной позиции, а не всего магазина.
    """

    # Двоеточие после имени поля указывает, данные какого типа здесь ожидаются.
    # Иконка — один текстовый символ (в этой программе обычно эмодзи товара).
    icon: str
    # Дату храним как date, а не как строку: так даты можно правильно сравнивать.
    release_date: date
    # Название и категория используются при выводе и поиске товаров.
    name: str
    category: str
    # Цена хранится целым числом рублей, рейтинг — дробным числом.
    price: int
    rating: float
    # amount показывает, сколько единиц товара сейчас осталось на складе.
    amount: int
    # Новый товар может ещё не иметь номера, поэтому кроме int разрешено значение None.
    # Поле с значением по умолчанию стоит последним — это требование dataclass.
    id: int | None = None

    def release_date_to_str(self) -> str:
        """Возвращает дату выпуска в удобном для человека виде: ДД.ММ.ГГГГ."""
        # self — конкретный товар, у которого был вызван этот метод.
        # strftime не изменяет исходную дату, а создаёт её строковое представление.
        # %d — день, %m — месяц, %Y — четырёхзначный год.
        return self.release_date.strftime("%d.%m.%Y")
