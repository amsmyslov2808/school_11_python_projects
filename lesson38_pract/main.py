# Класс Tamagochi из соседнего файла хранит состояние питомца и выполняет действия.
from tamagochi import Tamagochi

# Создаём одного питомца, состояние которого сохраняется между ходами.
tamagochi = Tamagochi("Тузик")

# Перед каждым ходом проверяем, жив ли питомец. Если is_dead() вернёт True,
# условие цикла станет ложным и меню больше не появится.
while tamagochi.is_dead() == False:
    # Пустые строки визуально отделяют показатели питомца от меню.
    print()
    tamagochi.print_info()
    print()

    print("Выберите действие:")
    print("1. Поиграть")
    print("2. Покормить")
    print("3. Уложить спать")
    print("4. Сменить имя")
    print("0. Выйти из игры")
    # input() возвращает строку, а int() преобразует её в число для сравнения
    # с номерами команд. Если строку нельзя преобразовать, возникнет ValueError.
    choosen_action = int(input("Напишите номер действия: "))

    print()

    # Цепочка if/elif выполняет одну подходящую ветку. Для числа вне меню
    # ни одна ветка не сработает и состояние питомца не изменится.
    if choosen_action == 1:
        tamagochi.play()
    elif choosen_action == 2:
        tamagochi.feed()
    elif choosen_action == 3:
        tamagochi.sleep()
    elif choosen_action == 4:
        name = input("Введите новое имя питомца: ")
        # Допустимость имени проверяет сам питомец в методе set_name().
        tamagochi.set_name(name)
    elif choosen_action == 0:
        # Завершаем программу с кодом 0, не дожидаясь нажатия Enter.
        exit(0)

    # Ждём Enter, чтобы игрок успел прочитать результат предыдущего действия.
    print()
    print("Для продолжения нажмите клавишу <enter>")
    input()
